import sqlite3
import pandas as pd

print("=== เริ่มต้นกระบวนการ Data Pipeline ===")

# -----------------------------------------------------------
# 1. EXTRACT: ดึงข้อมูลจากไฟล์ CSV
# -----------------------------------------------------------
print("\n[1] กำลังอ่านข้อมูลจาก raw_sales.csv...")
df_raw = pd.read_csv("raw_sales.csv")
print("ข้อมูลดิบทั้งหมด:")
print(df_raw)

# -----------------------------------------------------------
# 2. TRANSFORM: ตรวจสอบและทำความสะอาดข้อมูล
# -----------------------------------------------------------
print("\n[2] กำลังทำความสะอาดข้อมูล (ตัดรายการที่ราคา <= 0)...")
df_clean = df_raw[df_raw["price"] > 0]
print(f"ตัดข้อมูลผิดพลาดออก {len(df_raw) - len(df_clean)} รายการ")

# -----------------------------------------------------------
# 3. LOAD: นำข้อมูลสะอาดเข้าสู่ฐานข้อมูล SQLite
# -----------------------------------------------------------
print("\n[3] กำลังบันทึกข้อมูลลงฐานข้อมูล SQLite (sales.db)...")
# เชื่อมต่อกับไฟล์ฐานข้อมูล (ถ้ายังไม่มีไฟล์ ระบบจะสร้างให้ใหม่อัตโนมัติ)
conn = sqlite3.connect("sales.db")

# บันทึก DataFrame ลงตารางชื่อ 'orders'
df_clean.to_sql("orders", conn, if_exists="replace", index=False)
print("บันทึกข้อมูลเข้าสู่ฐานข้อมูลเรียบร้อย!")

# -----------------------------------------------------------
# 4. VERIFY: ลองเขียน SQL ดึงข้อมูลจากฐานข้อมูลมาตรวจสอบ
# -----------------------------------------------------------
print("\n[4] ตรวจสอบด้วยคำสั่ง SQL จากตาราง orders:")
query = "SELECT customer_name, SUM(price) as total_spent FROM orders GROUP BY customer_name;"
df_result = pd.read_sql(query, conn)
print(df_result)

# ปิดการเชื่อมต่อฐานข้อมูล
conn.close()
print("\n=== Data Pipeline ทำงานเสร็จสมบูรณ์! ===")